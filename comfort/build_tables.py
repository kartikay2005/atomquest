"""Build Duet's comfort tables from ASHRAE 55 (pythermalcomfort >= 4.7.0).

Outputs
  firmware/include/duet/comfort_table.h  int8 PMV x 50 tables the firmware ships with
  comfort/out/comfort_tables.json        the same tables plus metadata, for the docs
  comfort/out/truth_grid.npz             a dense float grid the twin uses to score comfort

Method
  pmv_ppd_ashrae(model='55-2023', airspeed_control=True): above 0.2 m/s the library
  applies ASHRAE 55's SET-based cooling effect, then PMV at still air.
  The Sleep profile uses met 0.8, below the library's 1.0 input limit, so it is
  generated with limit_inputs=False. This is stated in the report.

Assumptions (labelled, to calibrate in Round 3)
  FAN_AIR_SPEED: air speed at bed height per fan step, inside the 0.35-0.6 m/s room
  averages measured under ceiling fans (CBE). Step 0 = fan off = 0.10 m/s still air.
  RADIANT_OFFSET: firmware assumes mean radiant temperature = air + 1.0 C, because
  walls and ceiling run warmer than the AC-cooled air in a hot-dry summer.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pythermalcomfort
from pythermalcomfort.models import pmv_ppd_ashrae

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "comfort" / "out"
HEADER = ROOT / "firmware" / "include" / "duet" / "comfort_table.h"

T_MIN, T_MAX, T_STEP = 22.0, 34.0, 0.5
RH_MIN, RH_MAX, RH_STEP = 30.0, 90.0, 5.0
FAN_AIR_SPEED = [0.10, 0.15, 0.25, 0.35, 0.45, 0.60, 0.80]  # steps 0..6, m/s
RADIANT_OFFSET = 1.0
PMV_SCALE = 50  # int8 stores PMV * 50, clipped to +-2.5

PROFILES = {
    # name: (met, clo, limit_inputs)
    "evening": (1.0, 0.5, True),
    "sleep": (0.8, 0.9, False),  # light sleepwear + thin sheet + mattress
}


def pmv_grid(met: float, clo: float, limit: bool, temps, rhs, speeds, radiant_offset):
    t, rh, v = np.meshgrid(temps, rhs, speeds, indexing="ij")
    res = pmv_ppd_ashrae(
        tdb=t.ravel(),
        tr=(t + radiant_offset).ravel(),
        vr=v.ravel(),
        rh=rh.ravel(),
        met=met,
        clo=clo,
        model="55-2023",
        limit_inputs=limit,
        airspeed_control=True,
        round_output=False,
    )
    return np.asarray(res.pmv, dtype=float).reshape(t.shape)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    temps = np.arange(T_MIN, T_MAX + 1e-9, T_STEP)
    rhs = np.arange(RH_MIN, RH_MAX + 1e-9, RH_STEP)

    meta = {
        "library": f"pythermalcomfort {pythermalcomfort.__version__}",
        "function": "pmv_ppd_ashrae(model='55-2023', airspeed_control=True)",
        "t_axis": [T_MIN, T_MAX, T_STEP],
        "rh_axis": [RH_MIN, RH_MAX, RH_STEP],
        "fan_air_speed_mps": FAN_AIR_SPEED,
        "radiant_offset_c": RADIANT_OFFSET,
        "pmv_scale": PMV_SCALE,
        "profiles": {},
    }
    tables = {}
    for name, (met, clo, limit) in PROFILES.items():
        g = pmv_grid(met, clo, limit, temps, rhs, FAN_AIR_SPEED, RADIANT_OFFSET)
        if np.isnan(g).any():
            raise SystemExit(f"{name}: NaN in table ({np.isnan(g).sum()} cells)")
        q = np.clip(np.round(g * PMV_SCALE), -125, 125).astype(np.int8)
        tables[name] = q
        meta["profiles"][name] = {"met": met, "clo": clo, "limit_inputs": limit,
                                   "pmv_min": float(g.min()), "pmv_max": float(g.max())}

    # ---- C header -------------------------------------------------------
    nt, nrh, nv = len(temps), len(rhs), len(FAN_AIR_SPEED)
    lines = [
        "// GENERATED by comfort/build_tables.py - do not edit by hand.",
        f"// Source: {meta['library']}, {meta['function']}",
        "// Values are PMV x 50 (int8), indexed [temp][rh][fan_step].",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "namespace duet { namespace comfort {",
        f"constexpr float kTMin = {T_MIN}f, kTStep = {T_STEP}f;",
        f"constexpr float kRhMin = {RH_MIN}f, kRhStep = {RH_STEP}f;",
        f"constexpr int kNT = {nt}, kNRh = {nrh}, kNFan = {nv};",
        f"constexpr int kPmvScale = {PMV_SCALE};",
        "constexpr float kFanAirSpeed[kNFan] = {"
        + ", ".join(f"{v:.2f}f" for v in FAN_AIR_SPEED) + "};",
    ]
    for name, q in tables.items():
        lines.append(f"constexpr int8_t k{name.capitalize()}[kNT][kNRh][kNFan] = {{")
        for i in range(nt):
            rows = []
            for j in range(nrh):
                rows.append("{" + ",".join(str(int(x)) for x in q[i, j]) + "}")
            lines.append(f"  /* {temps[i]:.1f}C */ {{" + ",".join(rows) + "},")
        lines.append("};")
    lines += ["}}  // namespace duet::comfort", ""]
    HEADER.write_text("\n".join(lines))

    (OUT / "comfort_tables.json").write_text(json.dumps(
        {"meta": meta, "temps": temps.tolist(), "rhs": rhs.tolist(),
         **{k: v.tolist() for k, v in tables.items()}}, indent=1))

    # ---- dense truth grid for the twin (float, true radiant temp passed separately) ----
    # The twin scores comfort with its own mean radiant temperature, so the grid
    # is over (operative-ish) air temp and radiant delta.
    t_fine = np.arange(18.0, 38.0 + 1e-9, 0.25)
    rh_fine = np.arange(20.0, 95.0 + 1e-9, 2.5)
    d_fine = np.array([-1.0, 0.0, 1.0, 2.0, 3.0])  # tr - tdb
    truth = {}
    truth_profiles = dict(PROFILES)
    truth_profiles["blanket"] = (0.8, 1.4, False)   # sleeper who pulled up a blanket (twin only)
    for name, (met, clo, _) in truth_profiles.items():
        out = np.empty((len(t_fine), len(rh_fine), len(FAN_AIR_SPEED), len(d_fine)))
        for k, d in enumerate(d_fine):
            out[..., k] = pmv_grid(met, clo, False, t_fine, rh_fine, FAN_AIR_SPEED, d)
        truth[name] = out
    np.savez_compressed(OUT / "truth_grid.npz", t=t_fine, rh=rh_fine,
                        v=np.array(FAN_AIR_SPEED), d=d_fine, **truth)

    size = sum(q.size for q in tables.values())
    print(f"tables: {list(tables)} {nt}x{nrh}x{nv} -> {size} bytes total")
    for name, m in meta["profiles"].items():
        print(f"  {name}: PMV {m['pmv_min']:.2f} .. {m['pmv_max']:.2f}")
    print(f"header -> {HEADER.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
